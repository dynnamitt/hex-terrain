//! Drill mesh geometry: tapered 12-sided cylinder (16 segments, 2 bulges) + forked tip.
//! Generated from Blender via MCP — do not hand-edit vertex data.

use bevy::asset::RenderAssetUsages;
use bevy::mesh::Indices;
use bevy::prelude::Mesh;
use bevy::render::render_resource::PrimitiveTopology;

/// Fork gap Y in mesh-local space — laser fires from here.
pub const TIP_Y: f32 = -1.0;

/// Build a Bevy [`Mesh`] from the baked drill geometry.
///
/// Converts Blender coords (Z-up) → Bevy (Y-up), flipping the drill so
/// the fork tip points along −Y (forward after elbow rotation).
/// Flat-shaded: each triangle gets its own face normal.
pub fn build() -> Mesh {
    let positions: Vec<[f32; 3]> = VERTS.iter().map(|&[x, y, z]| [x, -z, y]).collect();
    // Reverse winding (single-axis negation flips handedness)
    let indices: Vec<u32> = INDICES.iter().flat_map(|&[a, b, c]| [a, c, b]).collect();

    let mut mesh = Mesh::new(
        PrimitiveTopology::TriangleList,
        RenderAssetUsages::default(),
    );
    mesh.insert_attribute(Mesh::ATTRIBUTE_POSITION, positions);
    mesh.insert_indices(Indices::U32(indices));
    mesh.duplicate_vertices();
    mesh.compute_flat_normals();
    mesh
}

